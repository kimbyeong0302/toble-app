async function main() {
  console.log('\n=== 룻기 character_profile ===');
  for (const p of RUTH_PEOPLE) {
    await upsertPerson('ruth', p.name, { character_profile: p.cp });
  }

  console.log('\n=== 마태복음 character_profile ===');
  for (const p of MATTHEW_PEOPLE) {
    await upsertPerson('matthew', p.name, { character_profile: p.cp });
  }

  console.log('\n=== 마가복음 character_profile ===');
  for (const p of MARK_PEOPLE) {
    await upsertPerson('mark', p.name, { character_profile: p.cp });
  }

  console.log('\n=== 누가복음 character_profile ===');
  for (const p of LUKE_PEOPLE) {
    await upsertPerson('luke', p.name, { character_profile: p.cp });
  }

  console.log('\n=== 요한복음 character_profile ===');
  for (const p of JOHN_PEOPLE) {
    await upsertPerson('john', p.name, { character_profile: p.cp });
  }

  console.log('\n=== 사도행전 body 확장 + character_profile ===');
  for (const p of ACTS_PEOPLE) {
    if (p.newBody) await updateBody('acts', p.name, p.newBody);
    if (p.cp) await upsertPerson('acts', p.name, { character_profile: p.cp });
  }

  console.log('\n=== 로마서 character_profile ===');
  for (const p of ROMANS_PEOPLE_UPDATE) {
    await upsertPerson('romans', p.name, { character_profile: p.cp });
    if (p.newBody) await updateBody('romans', p.name, p.newBody);
  }

  console.log('\n=== 로마서 누락 인물 추가 ===');
  for (const p of ROMANS_NEW_PEOPLE) {
    const { data: existing } = await sb.from('people').select('name').eq('book_id', 'romans').eq('name', p.name).maybeSingle();
    if (existing) { console.log(`  SKIP(exists) romans/${p.name}`); continue; }
    const payload = { book_id: 'romans', name: p.name, role: p.role, body: p.body, verse_ref: p.verse_ref };
    if (p.cp) payload.character_profile = p.cp;
    const { error } = await sb.from('people').insert(payload);
    if (error) console.error(`  FAIL insert romans/${p.name}:`, error.message);
    else console.log(`  INS romans/${p.name}`);
  }

  console.log('\n완료');
  process.exit(0);
}

main().catch(e => { console.error(e); process.exit(1); });
