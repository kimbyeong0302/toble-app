require('dotenv').config({ path: require('path').join(__dirname, '.env') });
const { createClient } = require('@supabase/supabase-js');
const sb = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);

// ── 헬퍼 ─────────────────────────────────────────────────────────

async function upsertPerson(bookId, name, fields) {
  // 이미 있으면 character_profile만 업데이트, 없으면 insert
  const { data: existing } = await sb.from('people').select('name,character_profile').eq('book_id', bookId).eq('name', name).maybeSingle();
  if (existing) {
    if (existing.character_profile && Object.keys(existing.character_profile).length > 0) {
      console.log(`  SKIP(cp exists) ${bookId}/${name}`);
      return;
    }
    const { error } = await sb.from('people').update(fields).eq('book_id', bookId).eq('name', name);
    if (error) console.error(`  FAIL update ${bookId}/${name}:`, error.message);
    else console.log(`  UP ${bookId}/${name}`);
  } else {
    const { error } = await sb.from('people').insert({ book_id: bookId, name, ...fields });
    if (error) console.error(`  FAIL insert ${bookId}/${name}:`, error.message);
    else console.log(`  INS ${bookId}/${name}`);
  }
}

async function updateBody(bookId, name, body) {
  const { error } = await sb.from('people').update({ body }).eq('book_id', bookId).eq('name', name);
  if (error) console.error(`  FAIL body ${bookId}/${name}:`, error.message);
  else console.log(`  BODY ${bookId}/${name}`);
}

